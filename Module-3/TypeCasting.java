public class TypeCasting {
    public static void main(String[] args) {
        double a = 25.75;
        int b = (int)a;
        System.out.println("Double = " + a);
        System.out.println("Int = " + b);
        int c = 50;
        double d = c;
        System.out.println("Int = " + c);
        System.out.println("Double = " + d);
    }
}